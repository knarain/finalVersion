interface DynamicSidebarProps {
  roleId: string
  currentPath?: string
}

export const DynamicSidebar: React.FC<DynamicSidebarProps> = ({ roleId, currentPath = '' }) => {
  const { permissions, loading, error, hasPermission } = usePermissions(roleId)
  const [expandedModules, setExpandedModules] = useState<Set<number>>(new Set())

  const toggleModule = (moduleId: number) => {
    const newExpanded = new Set(expandedModules)
    if (newExpanded.has(moduleId)) {
      newExpanded.delete(moduleId)
    } else {
      newExpanded.add(moduleId)
    }
    setExpandedModules(newExpanded)
  }

  const renderIcon = (iconName: string) => {
    const IconComponent = iconMap[iconName]
    return IconComponent ? <IconComponent /> : <iconMap.circle />
  }

  if (loading) {
    return (
      <div className="p-4">
        <div className="animate-pulse space-y-2">
          {[...Array(6)].map((_, i) => (
            <div key={i} className="h-10 bg-gray-200 rounded"></div>
          ))}
        </div>
      </div>
    )
  }

  if (error) {
    return (
      <div className="p-4 text-red-600">
        <p>Error loading menu: {error}</p>
      </div>
    )
  }

  return (
    <nav className="p-4 space-y-2">
      {permissions.map((rolePermission) => {
        const module = rolePermission.module_info
        const hasSubModules = rolePermission.sub_module_info.length > 0
        const isExpanded = expandedModules.has(module.id)
        const isActive = currentPath === module.url

        return (
          <div key={module.id} className="space-y-1">
            {/* Main Module */}
            <div className="flex items-center">
              {hasSubModules ? (
                <button
                  onClick={() => toggleModule(module.id)}
                  className={`flex items-center w-full px-3 py-2 text-sm font-medium rounded-lg transition-colors ${
                    isActive
                      ? 'bg-blue-100 text-blue-700'
                      : 'text-gray-700 hover:bg-gray-100'
                  }`}
                >
                  <span className="mr-3">{renderIcon(module.icon || 'folder')}</span>
                  <span className="flex-1 text-left">{module.name}</span>
                  {isExpanded ? (
                    <ChevronDown className="w-4 h-4" />
                  ) : (
                    <ChevronRight className="w-4 h-4" />
                  )}
                </button>
              ) : (
                <Link
                  href={module.url || '#'}
                  className={`flex items-center w-full px-3 py-2 text-sm font-medium rounded-lg transition-colors ${
                    isActive
                      ? 'bg-blue-100 text-blue-700'
                      : 'text-gray-700 hover:bg-gray-100'
                  }`}
                >
                  <span className="mr-3">{renderIcon(module.icon || 'folder')}</span>
                  <span>{module.name}</span>
                </Link>
              )}
            </div>

            {/* Sub-modules */}
            {hasSubModules && isExpanded && (
              <div className="ml-6 space-y-1">
                {rolePermission.sub_module_info.map((subModule) => {
                  const isSubActive = currentPath === subModule.url
                  
                  return (
                    <Link
                      key={subModule.id}
                      href={subModule.url || '#'}
                      className={`flex items-center px-3 py-2 text-sm rounded-lg transition-colors ${
                        isSubActive
                          ? 'bg-blue-50 text-blue-600 border-l-2 border-blue-600'
                          : 'text-gray-600 hover:bg-gray-50'
                      }`}
                    >
                      <span className="mr-3">{renderIcon(subModule.icon || 'circle')}</span>
                      <span>{subModule.name}</span>
                    </Link>
                  )
                })}
              </div>
            )}
          </div>
        )
      })}
    </nav>
  )
}

export default DynamicSidebar